import { describe, expect, it } from "vitest"
import { Redactor } from "../../security/redact.ts"
import { exchange, finding } from "./__fixtures__/report.ts"
import { ISSUE_REPRO_DIR, renderRepros, reproStem } from "./repro.ts"

describe("repro scripts", () => {
	it("replace the whole base URL, so a path prefix is not doubled", () => {
		const [script] = renderRepros(
			[finding({ evidence: [exchange({ url: "http://h.test/api/v1/rows" })] })],
			"http://h.test/api/",
			new Redactor(),
		)
		expect(script?.content).toContain('BASE="${BASE:-http://h.test/api}"')
		expect(script?.content).toContain('"$BASE/v1/rows"')
	})

	it("only abbreviate a URL that lies under the base path", () => {
		const [script] = renderRepros(
			[finding({ evidence: [exchange({ url: "http://h.test/apiv2/rows" })] })],
			"http://h.test/api",
			new Redactor(),
		)
		expect(script?.content).toContain("'http://h.test/apiv2/rows'")
		expect(script?.content).not.toContain("$BASE")
	})

	it("quote what they send, quotes included", () => {
		const [script] = renderRepros(
			[finding({ evidence: [exchange({ requestHeaders: { "x-note": "it's" }, url: "http://other.test/it's" })] })],
			"http://h.test",
			new Redactor(),
		)
		expect(script?.content).toContain(`'http://other.test/it'\\''s'`)
		expect(script?.content).toContain(`-H 'x-note: it'\\''s'`)
	})

	it("keep one file per finding when a check reports twice", () => {
		const scripts = renderRepros(
			[
				finding({ evidence: [exchange({ url: "http://h.test/a" })] }),
				finding({ evidence: [exchange({ url: "http://h.test/b" })] }),
				finding({ evidence: [exchange({ url: "http://h.test/c" })] }),
			],
			"http://h.test",
			new Redactor(),
		)
		expect(scripts.map((script) => script.filename)).toEqual([
			"row-sort-order-is-applied.sh",
			"row-sort-order-is-applied-2.sh",
			"row-sort-order-is-applied-3.sh",
		])
	})
})

describe("a repro script's content", () => {
	it("write a header naming the finding, then one curl per step, and skip findings with no evidence", () => {
		const detail = `${"word ".repeat(30)}end`
		const scripts = renderRepros(
			[
				finding({ evidence: [] }),
				finding({
					detail,
					entity: "table",
					evidence: [exchange({ status: 201 }), exchange({ status: 404 })],
					summary: "list is stale",
				}),
			],
			"http://h.test",
			new Redactor(),
		)
		expect(scripts).toHaveLength(1)
		const lines = scripts[0]?.content.split("\n") ?? []
		expect(lines.slice(0, 4)).toEqual([
			"#!/usr/bin/env bash",
			"# Generated by oat. Set TOKEN to a valid credential before running.",
			"#",
			"# table — list is stale",
		])
		expect(lines.filter((line) => line.startsWith("# word")).every((line) => line.length <= 90)).toBe(true)
		expect(lines).toContain("# step 1 — observed 201")
		expect(lines).toContain("# step 2 — observed 404")
		expect(lines).toContain('TOKEN="${TOKEN:?set TOKEN to a valid credential}"')
		expect(scripts[0]?.content.endsWith("\n")).toBe(true)
	})
})

describe("reproStem", () => {
	it("is the entity and check, slugged", () => {
		expect(reproStem(finding({ check: "patch.Preserves", entity: "Row" }))).toBe("row-patch-preserves")
		expect(ISSUE_REPRO_DIR).toBe("issue-repro")
	})
})
